<h3 class="wp-block-heading" style="font-size:1.8rem">9.1. Droit à la limitation et à l'opposition du traitement des données</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>L'utilisateur a le droit de demander la limitation ou de s'opposer au traitement de ses données par le site, sans que le site ne puisse refuser, sauf à démontrer l'existence de motifs légitimes et impérieux, pouvant prévaloir sur les intérêts et les droits et libertés de l'utilisateur. Afin de demander la limitation du traitement de ses données ou de formuler une opposition au traitement de ses données, l'utilisateur doit suivre la procédure suivante : l'utilisateur doit faire une demande de limitation au traitement de ses données personnelles auprès du responsable du traitement des données, en envoyant un email à l'adresse prévue ci-dessus.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"style":{"typography":{"fontSize":"1.8rem"}}} -->
<h3 class="wp-block-heading" style="font-size:1.8rem">9.2. Droit de ne pas faire l'objet d'une décision fondée exclusivement sur un procédé automatisé</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Conformément aux dispositions du règlement 2016/679, l'utilisateur a le droit de ne pas faire l'objet d'une décision fondée exclusivement sur un procédé automatisé si la décision produit des effets juridiques le concernant, ou l'affecte de manière significative de façon similaire.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"style":{"typography":{"fontSize":"1.8rem"}}} -->
