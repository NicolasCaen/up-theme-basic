<h2 class="wp-block-heading" style="font-size:2.2rem">Article 2 – PRINCIPES GÉNÉRAUX EN MATIÈRE DE COLLECTE ET DE TRAITEMENT DE DONNÉES</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Conformément aux dispositions de l'article 5 du Règlement européen 2016/679, la collecte et le traitement des données des utilisateurs du site respectent les principes suivants :</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Licéité, loyauté et transparence : les données ne peuvent être collectées et traitées qu'avec le consentement de l'utilisateur propriétaire des données. A chaque fois que des données à caractère personnel seront collectées, il sera indiqué à l'utilisateur que ses données sont collectées, et pour quelles raisons ses données sont collectées ;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Finalités limitées : la collecte et le traitement des données sont exécutés pour répondre à un ou plusieurs objectifs déterminés dans les présentes conditions générales d'utilisation ;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Minimisation de la collecte et du traitement des données : seules les données nécessaires à la bonne exécution des objectifs poursuivis par le site sont collectées ;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Conservation des données réduites dans le temps : les données sont conservées pour une durée limitée, dont l'utilisateur est informé.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Intégrité et confidentialité des données collectées et traitées : le responsable du traitement des données s'engage à garantir l'intégrité et la confidentialité des données collectées.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Afin d'être licites, et ce conformément aux exigences de l'article 6 du règlement européen 2016/679, la collecte et le traitement des données à caractère personnel ne pourront intervenir que s'ils respectent au moins l'une des conditions ci-après énumérées :</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>L'utilisateur a expressément consenti au traitement ;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Le traitement répond à une obligation légale ;</p>
