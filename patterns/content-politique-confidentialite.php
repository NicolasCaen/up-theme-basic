<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Il est rappelé à l'utilisateur qu'il peut organiser quel doit être le devenir de ses données collectées et traitées s'il décède, conformément à la loi n°2016-1321 du 7 octobre 2016.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"style":{"typography":{"fontSize":"1.8rem"}}} -->
<h3 class="wp-block-heading" style="font-size:1.8rem">9.4. Droit de saisir l'autorité de contrôle compétente</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Dans le cas où le responsable du traitement des données décide de ne pas répondre à la demande de l'utilisateur, et que l'utilisateur souhaite contester cette décision, ou, s'il pense qu'il est porté atteinte à l'un des droits énumérés ci-dessus, il est en droit de saisir la CNIL (Commission Nationale de l'Informatique et des Libertés,<a href="http://www.cnil.fr">www.cnil.fr</a>) ou tout juge compétent.</p>
